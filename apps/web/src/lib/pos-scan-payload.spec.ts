import { parsePOSScanPayload } from './pos-scan-payload';

describe('POS barcode and product QR decoding', () => {
  it('accepts EAN/UPC, Code 128 and plain QR text as inventory codes', () => {
    for (const code of ['4006381333931', '012345678905', 'ABC-123-456', 'SKU-A29']) {
      expect(parsePOSScanPayload('  ' + code + '  ')).toEqual({ kind: 'barcode', value: code });
    }
  });
  it('recognizes SmartDuka product QR payloads generated by QRCodeService', () => {
    const id = '507f1f77bcf86cd799439011';
    expect(parsePOSScanPayload(JSON.stringify({ type: 'product', id, name: 'Test' })))
      .toEqual({ kind: 'product-id', value: id });
  });
  it('never treats other QR types as sellable products', () => {
    for (const type of ['order', 'payment', 'loyalty']) {
      expect(parsePOSScanPayload(JSON.stringify({ type, id: '507f1f77bcf86cd799439011' })).kind)
        .toBe('unsupported');
    }
  });
  it('rejects untrusted URLs, payment cards and malformed product JSON', () => {
    for (const value of [
      'https://example.org/products/123', 'javascript:alert(1)',
      'BEGIN:VCARD\nTEL:123', '{broken', '{"type":"product","id":"not-an-object-id"}',
    ]) expect(parsePOSScanPayload(value).kind).toBe('unsupported');
  });
  it('rejects oversized, empty and control-character payloads', () => {
    expect(parsePOSScanPayload('  ').kind).toBe('unsupported');
    expect(parsePOSScanPayload('X'.repeat(200)).kind).toBe('unsupported');
    expect(parsePOSScanPayload('abc\u0000xyz').kind).toBe('unsupported');
  });
});
